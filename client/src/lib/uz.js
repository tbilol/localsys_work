// Oddiy matn uchun: t('welcome', { name: 'Ali' })
export function t(key, params = {}) {
  const template = uz[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

// Placeholder o'rniga React elementlari qo'yish uchun: rich('feed_task_create', { target: <b>…</b> })
export function rich(key, params = {}) {
  const template = uz[key] ?? key;
  return template.split(/(\{\w+\})/g).map((part, i) => {
    const m = /^\{(\w+)\}$/.exec(part);
    return m && m[1] in params ? createElement('span', { key: i }, params[m[1]]) : part;
  });
}
